/**
 * Preview stylesheet generation.
 *
 * The preview is scoped to the theme it is previewing, which means the theme
 * name is part of the CSS it produces: `spinPreset({themes: {[name]: tree}})`
 * emits `[data-theme="name"] { --color-primary: … }`, and the preview surface
 * carries that same `data-theme`. Passing the document rather than the parsed
 * tree is what lets `$extensions.spin.fonts` reach the preview — a parsed tree
 * keeps tokens and drops extensions, so a previewed font would silently not
 * load.
 */

import { spinClient } from "./client.ts";

/** Why a preview could not be generated. */
export interface PreviewFailure {
  readonly error: string;
}

/**
 * The preview stylesheet, generated by the daemon.
 *
 * The browser used to build this itself — @unocss/core plus the whole preset,
 * in order to answer a question the daemon answers in milliseconds. A studio
 * is a client; the stylesheet is server work.
 *
 * Failure is data. The preset refuses a theme that fails a legibility floor,
 * which is right for a build and wrong for a preview: the studio shows the
 * reason beside the theme that produced it, and the last good stylesheet
 * stays in place so an author mid-edit never loses the page.
 */
export async function previewCssSafely(
  text: string,
  name: string,
): Promise<string | PreviewFailure> {
  const out = await (await spinClient()).preview.css({ text, name });
  return out.error !== null ? { error: out.error } : out.css;
}

/**
 * The declarations a set of utilities resolve to, read out of a stylesheet.
 *
 * Still a string read rather than a query: the daemon returns CSS and the
 * utilities route asks what it says. A structured answer per utility would be
 * a better shape, but that is a contract change and this is a move.
 */
export function cssDeclarations(
  css: string,
  utilities: string[],
): Map<string, string> {
  const bodies = new Map<string, string>();
  for (const match of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const selector = match[1].trim();
    const body = match[2].trim().replace(/\s+/g, " ");
    const name = selector
      .split(",")[0]
      .trim()
      .replace(/^\./, "")
      .replace(/\\(.)/g, "$1");
    if (!bodies.has(name)) bodies.set(name, body);
  }
  const out = new Map<string, string>();
  for (const utility of utilities) {
    const body = bodies.get(utility);
    if (body !== undefined) out.set(utility, body);
  }
  return out;
}
