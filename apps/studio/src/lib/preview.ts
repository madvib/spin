/**
 * Preview stylesheet generation.
 *
 * The preview is scoped to the theme it is previewing, which means the theme
 * name is part of the CSS it produces: `spinPreset({themes: {[name]: tree}})`
 * emits `[data-theme="name"] { --color-primary: … }`, and the preview surface
 * carries that same `data-theme`. Passing the document rather than the parsed
 * tree is what lets `$extensions.spin.fonts` reach the preview — a parsed tree
 * keeps tokens and drops extensions, so a previewed font would silently not
 * load.
 */

import { spinClient } from "./client.ts";

/**
 * Paint custom properties onto the preview surface, and hand back the
 * function that takes them off again.
 *
 * This is how a drag previews without committing: every utility resolves
 * through the token's own custom property, so setting `--spacing-4` on the
 * element the stylesheet is scoped to moves every specimen that spends that
 * token, and removing it puts the document's word back. Inline declarations
 * win over the sheet on the same element; the chrome sits under a different
 * `data-theme` and never sees them. A caller that repaints must clear its
 * previous paint first — two painters on one variable cannot both take it
 * off.
 */
const paintedProps = new Set<string>();

function previewTargets(): HTMLElement[] {
  if (typeof document === "undefined") return [];
  const host = document.querySelector<HTMLElement>(".spin-preview[data-theme]");
  const specimens = Array.from(
    document.querySelectorAll<HTMLElement>(
      ".spin-preview [data-studio-specimen]",
    ),
  );
  return host === null ? specimens : [host, ...specimens];
}

export function clearPreviewPaint(): void {
  if (typeof document === "undefined") return;
  const targets = previewTargets();
  for (const el of targets) {
    for (const name of paintedProps) el.style.removeProperty(name);
  }
  paintedProps.clear();
}

export function paintPreview(vars: Record<string, string>): () => void {
  if (typeof document === "undefined") return () => {};
  const targets = previewTargets();
  if (targets.length === 0) return () => {};
  for (const [name, value] of Object.entries(vars)) {
    paintedProps.add(name);
    for (const el of targets) el.style.setProperty(name, value);
  }
  return () => {
    const current = previewTargets();
    for (const name of Object.keys(vars)) {
      for (const el of current) el.style.removeProperty(name);
    }
  };
}

/** Why a preview could not be generated. */
export interface PreviewFailure {
  readonly error: string;
}

/** What the preview resource fetches for, or `undefined` while the theme text has not arrived. */
export interface PreviewKey {
  readonly tree: unknown;
  readonly name: string;
  readonly markup?: string;
  readonly text: string;
}

/**
 * The preview resource key: present only once there is text to generate from.
 *
 * The registry answers after first paint, so the editor document starts
 * empty — and a fetch for empty text fails with an invalid-JSON banner
 * while leaving every specimen unstyled. No key, no fetch, no banner: the
 * last good stylesheet stays until the registry answers and the key lands.
 */
export function previewKey(
  text: string,
  name: string,
  tree: unknown,
  markup?: string,
): PreviewKey | undefined {
  if (text.trim() === "") return undefined;
  return { tree, name, markup, text };
}

/**
 * The preview stylesheet, generated by the daemon.
 *
 * The browser used to build this itself — @unocss/core plus the whole preset,
 * in order to answer a question the daemon answers in milliseconds. A studio
 * is a client; the stylesheet is server work.
 *
 * Failure is data. The preset refuses a theme that fails a legibility floor,
 * which is right for a build and wrong for a preview: the studio shows the
 * reason beside the theme that produced it, and the last good stylesheet
 * stays in place so an author mid-edit never loses the page.
 */
export async function previewCssSafely(
  text: string,
  name: string,
  markup?: string,
): Promise<string | PreviewFailure> {
  const out = await (await spinClient()).preview.css({ text, name, markup });
  return out.error !== null ? { error: out.error } : out.css;
}

/**
 * The declarations a set of utilities resolve to, read out of a stylesheet.
 *
 * Still a string read rather than a query: the daemon returns CSS and the
 * utilities route asks what it says. A structured answer per utility would be
 * a better shape, but that is a contract change and this is a move.
 */
export function cssDeclarations(
  css: string,
  utilities: string[],
): Map<string, string> {
  const bodies = new Map<string, string>();
  for (const match of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const selector = match[1].trim();
    const body = match[2].trim().replace(/\s+/g, " ");
    const name = selector
      .split(",")[0]
      .trim()
      .replace(/^\./, "")
      .replace(/\\(.)/g, "$1");
    if (!bodies.has(name)) bodies.set(name, body);
  }
  const out = new Map<string, string>();
  for (const utility of utilities) {
    const body = bodies.get(utility);
    if (body !== undefined) out.set(utility, body);
  }
  return out;
}
