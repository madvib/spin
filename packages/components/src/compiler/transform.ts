/**
 * The pure half of the `.html → define()` transform: markup in, module out.
 *
 * No filesystem, no bundler, no project root. The unplugin stage lives
 * composer-side and calls in with the source it loaded; includes and
 * actions arrive through injected readers because only the stage knows
 * where the project keeps them.
 */

import {
  expandVariantGroups,
  extractScript,
  parse,
  stripScript,
} from "@spinjs/components/runtime";
import { emit } from "./emit.ts";
export { emit, type EmitOutput } from "./emit.ts";

/** The virtual module that registers every project component. */
export const SPIN_COMPONENTS_ID = "spin/components";

/** Read a file's text, or throw naming it. The stage injects the fs. */
export type ReadFile = (path: string) => Promise<string>;

/** One action module beside a component: the import line and the registry entry. */
export interface ActionImports {
  readonly imports: string;
  readonly entries: readonly string[];
}

const sanitizePrefix = (raw: string): string => {
  let base = raw;
  const slash = base.lastIndexOf("/");
  if (slash >= 0) base = base.slice(slash + 1);
  const out = base.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
  return out === "" || out === "workspace" ? "app" : out;
};

/** The tag a project file registers, shared by the transform and the type writer. */
export function tagForProjectFile(
  file: string,
  componentsDir: string,
  prefix: string,
): string {
  const stem = file.split("/").pop()!.replace(/\.html$/, "");
  const parts = file.split("/");
  const at = parts.lastIndexOf(componentsDir.split("/").pop()!);
  const segments = at < 0 ? [] : parts.slice(at + 1, -1);
  if (stem.startsWith(`${prefix}-`) || stem.startsWith("spin-")) return stem;
  return [prefix, ...segments, stem].join("-");
}

/** The body of the virtual registration module: one side-effect import per file. */
export function renderComponentsModule(
  files: readonly string[],
): string {
  return files.map((file) => `import "/${file}";`).join("\n") + "\n";
}

/** The project's component tags as JSX types. */
export function renderComponentsDts(tags: readonly string[]): string {
  const allTags = [...new Set(tags)].sort();
  const globalEntries = allTags.map((tag) =>
    `    "${tag}": HTMLElement & SpinProjectComponentAttributes;`
  ).join("\n");
  const jsxEntries = allTags.map((tag) =>
    `      "${tag}": SpinProjectComponentAttributes;`
  ).join("\n");
  return [
    "/**",
    " * The project's own components, for TypeScript — every framework, and none.",
    " *",
    " * GENERATED by the spin components stage from src/lib/components. Do not edit by hand.",
    " */",
    "export {};",
    "",
    'declare module "spin/styles.css";',
    'declare module "spin.css";',
    'declare module "uno.css";',
    'declare module "spin/components";',
    "/** What every project component accepts: a ref, common attributes, and machine props. */",
    "interface SpinProjectComponentAttributes {",
    "  ref?: HTMLElement | ((el: HTMLElement) => void);",
    "  class?: string;",
    "  id?: string;",
    "  role?: string;",
    "  title?: string;",
    "  children?: unknown;",
    "  [attribute: string]: unknown;",
    "}",
    "",
    "declare global {",
    "  interface HTMLElementTagNameMap {",
    globalEntries,
    "  }",
    "}",
    "",
    'declare module "solid-js" {',
    "  namespace JSX {",
    "    interface IntrinsicElements {",
    jsxEntries,
    "    }",
    "  }",
    "}",
    "",
  ].join("\n");
}

/**
 * The includes in a markup: `<include file="./_markup.html" />`.
 *
 * A family's markup lives ONCE, and its examples are that markup with
 * their own parameters. The include is resolved textually, before the
 * parse, so the parser never sees it: the included file's body is
 * inlined, and the INCLUDING file's scope decl stands (the included
 * file's own scope decl is dropped — it is the family's, and the
 * example's is narrower).
 */
export async function resolveIncludes(
  source: string,
  id: string,
  readFile: ReadFile,
): Promise<string> {
  const file = id.split("?")[0]!;
  const dir = file.split("/").slice(0, -1).join("/");
  let code = source;
  for (let pass = 0; pass < 8; pass += 1) {
    const m = /<include\s+file="([^"]+)"\s*\/?>/.exec(code);
    if (m === null) break;
    const target = m[1]!;
    const path = target.startsWith("/") ? target.slice(1) : `${dir}/${target}`;
    const resolved = path.split("/").reduce((parts, part) => {
      if (part === "..") return parts.slice(0, -1);
      if (part === ".") return parts;
      return [...parts, part];
    }, [] as string[]).join("/");
    let included: string;
    try {
      included = await readFile(resolved);
    } catch {
      throw new Error(
        `spin-components: ${id} includes ${target}, which is not there`,
      );
    }
    const body = included
      .replace(/<script(\s[^>]*)?>[\s\S]*?<\/script>\s*/, "");
    code = code.replace(m[0], body);
  }
  return code;
}

/** Everything the transform needs beyond the markup itself. */
export interface TransformInput {
  /** The bundler id, `?spin-component` suffix included. */
  readonly id: string;
  /** The custom-element tag this module defines. */
  readonly tag: string;
  /** The action imports the stage resolved beside the file. */
  readonly actions: ActionImports;
}

/**
 * Markup to module: strip comments, expand groups, extract the script,
 * parse, emit, and wrap in `define()`. The stage resolved the tag and
 * the actions; this assembles them.
 */
export function transformMarkup(source: string, input: TransformInput): string {
  const code = expandVariantGroups(source.replace(/<!--[\s\S]*?-->/g, ""));
  const scriptSource = extractScript(code);
  const script = scriptSource === undefined
    ? undefined
    : stripScript(scriptSource);
  const markup = scriptSource === undefined
    ? code
    : code.replace(/<script(\s[^>]*)?>[\s\S]*?<\/script>\s*/g, "");
  if (/<!doctype|<style[\s>]/i.test(markup)) {
    throw new Error(
      `spin-components: ${input.id} looks like a document, not a component`,
    );
  }
  const ir = parse(markup);
  const { js } = emit(ir);
  const scriptBindings = script?.calls ?? [];
  const body = js
    .replace(
      /^export function create\(ctx, actions\) \{/,
      "export function create(actions, values) {",
    )
    .replace(/void ctx;\n/, "");
  const scriptImports: string[] = [];
  if (script !== undefined) {
    for (
      const m of script.module.matchAll(
        /^\s*import(?:\s|\{|\*)[\s\S]*?from\s*["'][^"']+["']\s*;?/gm,
      )
    ) {
      scriptImports.push(m[0].trim());
    }
  }
  const scriptCalls: string[] = [];
  if (script !== undefined) {
    for (const c of script.consumes) {
      scriptCalls.push(`  const ${c.name} = consume(${c.handle});`);
    }
    for (const binding of scriptBindings) {
      const bridge = `${binding.name}Bridge`;
      const component = `${binding.factory}`;
      scriptCalls.push(
        `  const ${bridge}Events = Object.fromEntries(Object.entries(${component}.events ?? {}).map(([eventName, contract]) => [contract.on, (details) => { el.dispatchEvent(new CustomEvent(eventName, { detail: contract.detail(details), bubbles: true })); }]));\n` +
        `  const ${bridge}Script = ${binding.args || "{}"};\n` +
        `  const ${bridge}Props = () => { const p = { ...${bridge}Script, ...props, ...${bridge}Events }; delete p["@@resolve"]; delete p["@@slots"]; p["@@authored"] = (name) => authored(name) || name in ${bridge}Script; return p; };\n` +
          `  const ${bridge} = watch(${component}, () => "createBridge" in ${component}\n` +
          `    ? ${component}.createBridge(${bridge}Props, () => el, bridgeId(el, ${JSON.stringify(input.tag)}, ${JSON.stringify(binding.name)}))\n` +
          `    : { api: ${component}.attach(el), dispose() {} }, ${component}.commands, ${JSON.stringify(binding.name)});\n` +
          `  values[${JSON.stringify(binding.name)}] = ${bridge}.api;\n` +
          `  for (const command of ${component}.commands ?? []) el[command] = (...args) => ${bridge}.api[command](...args);\n`
      );
    }
  }
  const hasConsume = scriptCalls.length > 0;
  const hasBindings = scriptBindings.length > 0;
  const componentRefs = scriptBindings.map((b) => b.factory);
  const fieldsExpr = hasConsume && componentRefs.length > 0
    ? `[...new Set([${componentRefs.map((c) => `...(${c}.fields ?? [])`).join(", ")}])]`
    : "[]";
  const buildParams = hasConsume ? "el, props, watch, consume, authored" : "el";
  const runtimeImport = hasConsume
    ? `import { define, uniqueId, projectSlots } from "@spinjs/components/runtime";`
    : `import { define, projectSlots } from "@spinjs/components/runtime";`;
  const bridgeIdHelper = hasBindings
    ? "const bridgeId = (el, tag, name) => el.id !== \"\" ? `${el.id}:${name}` : uniqueId(`${tag}-${name}`);"
    : "";
  const defineHead = hasConsume
    ? `define(${JSON.stringify(input.tag)}, { props: ${fieldsExpr}, build({ ${buildParams} }) {`
    : `define(${JSON.stringify(input.tag)}, { build({ ${buildParams} }) {`;
  const file = input.id.split("?")[0]!;
  return [
    runtimeImport,
    input.actions.imports,
    ...scriptImports,
    `const actions = { ${input.actions.entries.join(", ")} };`,
    ...(bridgeIdHelper === "" ? [] : [bridgeIdHelper]),
    body,
    `/* spin-components v1 ${input.tag} */`,
    defineHead,
    `  const values = {};`,
    ...scriptCalls,
    `  values["@@slots"] = projectSlots(el);`,
    `  const { nodes } = create(actions, values, el);`,
    `  for (const node of nodes) el.appendChild(node);`,
    `} });`,
    ...(file.includes("/examples/")
      ? [`if (import.meta.hot) import.meta.hot.accept(() => import.meta.hot.invalidate());`]
      : []),
    `export default ${JSON.stringify(input.tag)};`,
  ].join("\n");
}

