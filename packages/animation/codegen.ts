/**
 * Emits `src/styles.ts` from the CSS source.
 *
 * The stylesheet stays a real `.css` file (highlighting, formatting, linting),
 * but nothing at runtime imports it: bundlers outside Deno — Rolldown in
 * particular — refuse to bundle CSS-as-text, and `with { type: "text" }` does
 * not exist in browsers at all. The generated module is plain strings,
 * loadable everywhere. Run after editing `animation.css`.
 */

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const HERE = new URL("./src/", import.meta.url);
const OUT = fileURLToPath(new URL("./src/styles.ts", import.meta.url));

const css = await readFile(new URL("./animation.css", HERE), "utf8");
const parts = [
  "// Generated by `bun run codegen` in packages/animation. Do not edit.",
  "// Source of truth is animation.css beside it.",
  "",
  `export const animationCss: string = ${JSON.stringify(css)};`,
];

await writeFile(OUT, parts.join("\n"));
console.log("styles.ts written");
