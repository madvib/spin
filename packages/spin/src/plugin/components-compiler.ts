import type { UnpluginOptions } from "unplugin";
import {
  expandVariantGroups,
  extractScript,
  parse,
  stripScript,
} from "@spinjs/runtime";
import { emit } from "../compiler/emit.ts";

/**
 * The `.html → define()` stage: compiles a component example into a
 * custom element. Consume names resolve beside the markup first (the
 * machine's own example) and fall back to `@spinjs/components`, so a
 * markup that lives outside the package needs no path option.
 */
export interface SpinComponentsOptions {
  /** Project directory holding user-authored `.html` components. Default `"src/lib/components"`. */
  readonly componentsDir?: string;
  /** Custom-element prefix for files under `componentsDir`. Defaults to the sanitized package name, else `"app"`. */
  readonly prefix?: string;
  /** Fallback prefix when no package name resolves. Default `"app"`. */
  readonly fallbackPrefix?: string;
}

/** The virtual module that registers every project component. */
export const SPIN_COMPONENTS_ID = "spin/components";

const sanitizePrefix = (raw: string): string => {
  let base = raw;
  const slash = base.lastIndexOf("/");
  if (slash >= 0) base = base.slice(slash + 1);
  const out = base.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
  return out === "" || out === "workspace" ? "app" : out;
};

/** The tag a project file registers, shared by the transform and the type writer. */
export function tagForProjectFile(
  file: string,
  componentsDir: string,
  prefix: string,
): string {
  const stem = file.split("/").pop()!.replace(/\.html$/, "");
  const parts = file.split("/");
  const at = parts.lastIndexOf(componentsDir.split("/").pop()!);
  const segments = at < 0 ? [] : parts.slice(at + 1, -1);
  if (stem.startsWith(`${prefix}-`) || stem.startsWith("spin-")) return stem;
  return [prefix, ...segments, stem].join("-");
}

/** Every `.html` component under a directory, relative to the project root. */
export async function projectComponentFiles(
  root: string,
  componentsDir: string,
): Promise<string[]> {
  const path = await import("node:path");
  const fs = await import("node:fs/promises");
  const { resolveProjectDir } = await import("../project/resolve-dir.ts");
  const resolved = await resolveProjectDir(root, componentsDir, "components");
  if (resolved.file) {
    return resolved.path.endsWith(".html")
      ? [path.relative(root, resolved.path).split(path.sep).join("/")]
      : [];
  }
  const out: string[] = [];
  const walk = async (dir: string): Promise<void> => {
    let entries;
    try {
      entries = await fs.readdir(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) await walk(full);
      else if (entry.isFile() && entry.name.endsWith(".html")) {
        out.push(path.relative(root, full).split(path.sep).join("/"));
      }
    }
  };
  await walk(resolved.path);
  return out.sort();
}

/** The body of the virtual registration module: one side-effect import per file. */
export function renderComponentsModule(
  files: readonly string[],
): string {
  // Every file is under the project root — the components directory is
  // always local — so every import is root-anchored and the stage
  // resolves it against the project it serves.
  return files.map((file) => `import "/${file}";`).join("\n") + "\n";
}

