/** The project's component tags and Spin primitive tags as JSX types. */
export function renderComponentsDts(tags: readonly string[]): string {
  const allTags = [...new Set([...PRIMITIVE_CUSTOM_TAGS, ...tags])].sort();
  const globalEntries = allTags.map((tag) =>
    `    "${tag}": HTMLElement & SpinProjectComponentAttributes;`
  ).join("\n");
  const jsxEntries = allTags.map((tag) =>
    `      "${tag}": SpinProjectComponentAttributes;`
  ).join("\n");
  return [
    "/**",
    " * The project's own components, for TypeScript — every framework, and none.",
    " *",
    " * GENERATED by the spin components stage from src/lib/components. Do not edit by hand.",
    " */",
    "export {};",
    "",
    'declare module "spin/styles.css";',
    'declare module "spin.css";',
    'declare module "uno.css";',
    'declare module "spin/components";',
    "/** What every project component accepts: a ref, common attributes, and machine props. */",
    "interface SpinProjectComponentAttributes {",
    "  ref?: HTMLElement | ((el: HTMLElement) => void);",
    "  class?: string;",
    "  id?: string;",
    "  role?: string;",
    "  title?: string;",
    "  children?: unknown;",
    "  [attribute: string]: unknown;",
    "}",
    "",
    "declare global {",
    "  interface HTMLElementTagNameMap {",
    globalEntries,
    "  }",
    "}",
    "",
    'declare module "solid-js" {',
    "  namespace JSX {",
    "    interface IntrinsicElements {",
    jsxEntries,
    "    }",
    "  }",
    "}",
    "",
  ].join("\n");
}
const resolvePrefixForFile = async (
  file: string,
  options: SpinComponentsOptions = {},
): Promise<string> => {
  if (options.prefix !== undefined) return options.prefix;
  if (options.fallbackPrefix !== undefined) return options.fallbackPrefix;
  try {
    const path = await import("node:path");
    const fs = await import("node:fs/promises");
    let dir = path.dirname(file);
    for (let depth = 0; depth < 6; depth++) {
      try {
        const raw = await fs.readFile(path.join(dir, "package.json"), "utf8");
        const name = (JSON.parse(raw) as { name?: unknown }).name;
        if (typeof name === "string" && name.length > 0) {
          return sanitizePrefix(name);
        }
      } catch {
      }
      const parent = path.dirname(dir);
      if (parent === dir) break;
      dir = parent;
    }
  } catch {
  }
  return "app";
};

/** Write or refresh `src/spin-components.d.ts` (or `src/lib/components/components.d.ts` during build). */
export async function writeProjectComponentsDts(
  projectRoot: string,
  options: SpinComponentsOptions = {},
  mode: { readonly onlyIfSrcExists?: boolean } = {},
): Promise<void> {
  const fs = await import("node:fs/promises");
  const path = await import("node:path");
  const { resolveProjectDir } = await import("../project/resolve-dir.ts");
  const componentsDir = options.componentsDir ?? "src/lib/components";
  let srcIsDir = false;
  try {
    srcIsDir = (await fs.stat(path.join(projectRoot, "src"))).isDirectory();
  } catch {
    srcIsDir = false;
  }
  if (mode.onlyIfSrcExists && !srcIsDir) return;
  const files = await projectComponentFiles(projectRoot, componentsDir);
  const probe = files.length > 0
    ? `${projectRoot}/${files[0]}`
    : `${projectRoot}/package.json`;
  const prefix = await resolvePrefixForFile(probe, options);
  const resolved = (await resolveProjectDir(projectRoot, componentsDir, "components")).path;
  const tags = files.map((file) =>
    tagForProjectFile(`${projectRoot}/${file}`, resolved, prefix)
  );
  const body = renderComponentsDts(tags);
  const same = async (file: string): Promise<boolean> => {
    try {
      return (await fs.readFile(file, "utf8")) === body;
    } catch {
      return false;
    }
  };
  if (srcIsDir) {
    const out = path.join(projectRoot, "src", "spin-components.d.ts");
    if (!(await same(out))) await fs.writeFile(out, body);
    return;
  }
  const out = path.join(resolved, "components.d.ts");
  if (!(await same(out))) await fs.writeFile(out, body);
}

export function spinComponentsStage(options: SpinComponentsOptions = {}): UnpluginOptions {
  const actionsDir = "actions";
  const componentsDir = options.componentsDir ?? "src/lib/components";
  let projectRoot = process.cwd();
  let cachedPrefix: string | undefined;
  // The prefix belongs to the project that serves the tree: the walk
  // starts at the file and reads the nearest manifest with a name.
  const prefixOf = async (file: string): Promise<string> => {
    if (options.prefix !== undefined) return options.prefix;
    if (options.fallbackPrefix !== undefined) return options.fallbackPrefix;
    if (cachedPrefix !== undefined) return cachedPrefix;
    try {
      const path = await import("node:path");
      const fs = await import("node:fs/promises");
      let dir = path.dirname(file);
      for (let depth = 0; depth < 6; depth++) {
        try {
          const raw = await fs.readFile(path.join(dir, "package.json"), "utf8");
          const name = (JSON.parse(raw) as { name?: unknown }).name;
          if (typeof name === "string" && name.length > 0) {
            cachedPrefix = sanitizePrefix(name);
            return cachedPrefix;
          }
        } catch {
        }
        const parent = path.dirname(dir);
        if (parent === dir) break;
        dir = parent;
      }
    } catch {
    }
    cachedPrefix = "app";
    return cachedPrefix;
  };
  const isUnderDir = (file: string, dir: string): boolean =>
    file.split("/").join("/").includes(`/${dir}/`);
  // The resolved components tree: the tag derivation reads the resolved
  // path's own leaf, so the segments under it are the tag's middle.
  const resolvedDirOf = async (): Promise<string> => {
    const { resolveProjectDir } = await import("../project/resolve-dir.ts");
    return (await resolveProjectDir(projectRoot, componentsDir, "components")).path;
  };
  const tagsForDts = async (): Promise<string[]> => {
    const files = await projectComponentFiles(projectRoot, componentsDir);
    const probe = files.length > 0 ? `${projectRoot}/${files[0]}` : `${projectRoot}/package.json`;
    const prefix = await prefixOf(probe);
    const resolved = await resolvedDirOf();
    return files.map((file) =>
      tagForProjectFile(`${projectRoot}/${file}`, resolved, prefix)
    );
  };
  const writeDts = async (): Promise<void> => {
    await writeProjectComponentsDts(projectRoot, options);
  };
  return {
    name: "spin-components",
    enforce: "pre",
    vite: {
      configResolved(config: { root: string }): void {
        projectRoot = config.root;
      },
    },
    async buildStart() {
      await writeDts();
    },
    async resolveId(id, importer) {
      if (id === SPIN_COMPONENTS_ID || id === `\0${SPIN_COMPONENTS_ID}`) {
        return `\0${SPIN_COMPONENTS_ID}`;
      }
      if (
        id.startsWith("@spinjs/components/") && id.endsWith(".html")
      ) {
        const path = await import("node:path");
        const { createRequire } = await import("node:module");
        const machines = path.dirname(
          createRequire(import.meta.url).resolve("@spinjs/components"),
        );
        return `${path.join(machines, id.slice("@spinjs/components/".length))}?spin-component`;
      }
      if (
        (id.startsWith(`${componentsDir}/`) || id.startsWith(`/${componentsDir}/`)) &&
        id.endsWith(".html")
      ) {
        const path = await import("node:path");
        const rel = id.startsWith("/") ? id.slice(1) : id;
        return `${path.resolve(projectRoot, rel)}?spin-component`;
      }
      // `?raw` / `?url` imports want the file, not the element: the
      // reference app reads example sources as text through globs.
      if (id.includes("?raw") || id.includes("?url")) return undefined;
      if (
        id === "index.html" ||
        id.endsWith("/index.html") ||
        id.endsWith("\\index.html")
      ) {
        return undefined;
      }
      if (
        id.endsWith(".html") && importer && !importer.includes("node_modules")
      ) {
        const path = await import("node:path");
        const real = path.resolve(path.dirname(importer.split("?")[0]!), id);
        return `${real}?spin-component`;
      }
      return undefined;
    },
    loadInclude(id) {
      return id.endsWith("?spin-component") || id === `\0${SPIN_COMPONENTS_ID}`;
    },
    async load(id) {
      if (id === `\0${SPIN_COMPONENTS_ID}`) {
        const files = await projectComponentFiles(projectRoot, componentsDir);
        return renderComponentsModule(files);
      }
      const real = id.split("?")[0]!;
      const path = await import("node:path");
      const fs = await import("node:fs/promises");
      // The dependency scanner can hand a root-anchored project file back
      // without its leading slash; resolve it against the project root so
      // the scan does not read a path relative to the process cwd.
      const file = path.isAbsolute(real) ? real : path.resolve(projectRoot, real);
      return fs.readFile(file, "utf8");
    },
    transformInclude(id) {
      return id.endsWith("?spin-component");
    },
    async transform(source, id) {
      if (isUnderDir(id.split("?")[0]!, componentsDir)) void writeDts();
      // Example notes live in HTML comments (rendered in the code tab);
      // they are source-only and never reach the IR.
      // The includes are resolved BEFORE the parse: the parser never
      // sees them, and the included file's body is inlined.
      const code = expandVariantGroups(
        (await resolveIncludes(source.replace(/<!--[\s\S]*?-->/g, ""), id))
          .code,
      );
      // A script block is the component's own TypeScript: extract it before
      // the parse, so the markup parser never sees it.
      const scriptSource = extractScript(code);
      const script = scriptSource === undefined
        ? undefined
        : stripScript(scriptSource);
      const markup = scriptSource === undefined
        ? code
        : code.replace(/<script(\s[^>]*)?>[\s\S]*?<\/script>\s*/g, "");
      if (/<!doctype|<style[\s>]/i.test(markup)) {
        throw new Error(
          `spin-components: ${id} looks like a document, not a component`,
        );
      }
      const file = id.split("?")[0]!;
      const stem = file.split("/").pop()!.replace(/\.html$/, "");
      const parentDir = file.split("/").slice(-2, -1)[0] ?? "";
      const grandparent = file.split("/").slice(-3, -2)[0] ?? "";
      const machine = parentDir === "examples"
        ? (grandparent.startsWith("spin-")
          ? grandparent.slice("spin-".length)
          : grandparent)
        : "";
      // Catalog examples keep their machine-qualified tag
      // (`tree-view-basic`); project components under `componentsDir` take
      // the project prefix (`<prefix>-<dir>-<stem>`).
      let tag: string;
      if (machine.length > 0) {
        tag = `${machine}-${stem}`;
      } else if (isUnderDir(file, componentsDir) || isUnderDir(file, await resolvedDirOf())) {
        tag = tagForProjectFile(file, await resolvedDirOf(), await prefixOf(file));
      } else {
        tag = stem;
      }
      const dir = file.split("/").slice(0, -1).join("/");
      const { parse: parseMod } = await import("@spinjs/runtime");
      void parseMod;
      const ir = parse(markup);
      const { js } = emit(ir);
      // Script bindings: `const machine = slider({...})` — the machine is
      // a function, call it. Each binding becomes a bridge under its own
      // name, with the call's args object as the props seed. No coercion:
      // the checker guarantees the args.
      const scriptBindings = script?.calls ?? [];
      const body = js
        .replace(
          /^export function create\(ctx, actions\) \{/,
          "export function create(actions, values) {",
        )
        .replace(/void ctx;\n/, "");
      const fs = await import("node:fs/promises");
      const path = await import("node:path");
      const findActions = async (
        start: string,
      ): Promise<string | undefined> => {
        let current = start;
        for (let depth = 0; depth < 4; depth++) {
          try {
            const entries = await fs.readdir(path.join(current, actionsDir));
            void entries;
            return path.join(current, actionsDir);
          } catch {
            // Walk up: elements/accordion-root.html looks beside itself,
            // then in the component directory above.
          }
          const parent = path.dirname(current);
          if (parent === current) return undefined;
          current = parent;
        }
        return undefined;
      };
      const actionsPath = await findActions(dir);
      let actionImports = "";
      const actionNames: string[] = [];
      try {
        if (!actionsPath) throw new Error("no actions");
        const files = await fs.readdir(actionsPath);
        for (const f of files) {
          if (!f.endsWith(".action.ts")) continue;
          const mod = `./${path.relative(dir, actionsPath)}/${f}`;
          const src = await fs.readFile(path.join(actionsPath, f), "utf8");
          const names = [...src.matchAll(/export const (\w+)/g)].map((m) =>
            m[1]!
          );
          for (const name of names) {
            const alias = `${name}_${actionNames.length}`;
            actionImports += `import { ${name} as ${alias} } from ${
              JSON.stringify(mod)
            };\n`;
            actionNames.push(`${JSON.stringify(name)}: ${alias}`);
          }
        }
      } catch {
        // No actions directory: markup wires no actions.
      }
      // Script imports pass through verbatim: the script names its
      // component, and the checker (not a convention walk) resolves it.
      // The `<script>` imports the callable presentation directly
      // (`../slider.presentation.ts`): the factory is the type source and
      // the runtime source, carrying `.createBridge`, `.commands`,
      // `.events`, and `.manifest`.
      const scriptImports: string[] = [];
      if (script !== undefined) {
        for (
          const m of script.module.matchAll(
            /^\s*import(?:\s|\{|\*)[\s\S]*?from\s*["'][^"']+["']\s*;?/gm,
          )
        ) {
          scriptImports.push(m[0].trim());
        }
      }
      // Script bindings become bridges under their own names. The script
      // calls the presentation's callable (typed args, checked by the gate);
      // the plugin pairs it with the same module for the bridge. The
      // presentation found the way consume finds defs: `<name>.presentation.ts`.
      const scriptCalls: string[] = [];
      if (script !== undefined) {
        for (const c of script.consumes) {
          scriptCalls.push(`  const ${c.name} = consume(${c.handle});`);
        }
        for (const binding of scriptBindings) {
          const bridge = `${binding.name}Bridge`;
          const component = `${binding.factory}`;
          scriptCalls.push(
            `  const ${bridge}Events = Object.fromEntries(Object.entries(${component}.events ?? {}).map(([eventName, contract]) => [contract.on, (details) => { el.dispatchEvent(new CustomEvent(eventName, { detail: contract.detail(details), bubbles: true })); }]));\n` +
            `  const ${bridge}Script = ${binding.args || "{}"};\n` +
            `  const ${bridge}Props = () => { const p = { ...${bridge}Script, ...props, ...${bridge}Events }; delete p["@@resolve"]; delete p["@@slots"]; p["@@authored"] = (name) => authored(name) || name in ${bridge}Script; return p; };\n` +
              `  const ${bridge} = watch(${component}, () => "createBridge" in ${component}\n` +
              `    ? ${component}.createBridge(${bridge}Props, () => el, bridgeId(el, ${JSON.stringify(tag)}, ${JSON.stringify(binding.name)}))\n` +
              `    : { api: ${component}.attach(el), dispose() {} }, ${component}.commands, ${JSON.stringify(binding.name)});\n` +
              `  values[${JSON.stringify(binding.name)}] = ${bridge}.api;\n` +
              `  for (const command of ${component}.commands ?? []) el[command] = (...args) => ${bridge}.api[command](...args);\n`
          );
        }
      }
      const hasConsume = scriptCalls.length > 0;
      const hasBindings = scriptBindings.length > 0;
      const componentRefs = scriptBindings.map((b) => b.factory);
      const fieldsExpr = hasConsume && componentRefs.length > 0
        ? `[...new Set([${componentRefs.map((c) => `...(${c}.fields ?? [])`).join(", ")}])]`
        : "[]";
      const buildParams = hasConsume ? "el, props, watch, consume, authored" : "el";
      const runtimeImport = hasConsume
        ? `import { define, uniqueId, projectSlots } from "@spinjs/runtime";`
        : `import { define, projectSlots } from "@spinjs/runtime";`;
      const bridgeIdHelper = hasBindings
        ? "const bridgeId = (el, tag, name) => el.id !== \"\" ? `${el.id}:${name}` : uniqueId(`${tag}-${name}`);"
        : "";
      const defineHead = hasConsume
        ? `define(${JSON.stringify(tag)}, { props: ${fieldsExpr}, build({ ${buildParams} }) {`
        : `define(${JSON.stringify(tag)}, { build({ ${buildParams} }) {`;
      return {
        code: [
          runtimeImport,
          actionImports,
          ...scriptImports,
          `const actions = { ${actionNames.join(", ")} };`,
          ...(bridgeIdHelper === "" ? [] : [bridgeIdHelper]),
          body,
          `/* spin-components v1 ${tag} */`,
          defineHead,
          `  const values = {};`,
          ...scriptCalls,
          // Light-DOM children are projected BEFORE create(): the markup's
          // `<slot>` points resolve against this map. Reserved like
          // `@@resolve` — never a machine prop (see the deletes above).
          `  values["@@slots"] = projectSlots(el);`,
          `  const { nodes } = create(actions, values, el);`,
          `  for (const node of nodes) el.appendChild(node);`,
          `} });`,
          // Example modules cannot hot-swap: the tag is already defined and
          // the define guard keeps the first registration, so an edit would
          // serve stale markup forever. Invalidate (full reload) instead.
          ...(file.includes("/examples/")
            ? [`if (import.meta.hot) import.meta.hot.accept(() => import.meta.hot.invalidate());`]
            : []),
          `export default ${JSON.stringify(tag)};`,
        ].join("\n"),
        map: null,
      };
    },
  };
}

/**
 * The includes in a markup: `<include file="./_markup.html" />`.
 *
 * A family's markup lives ONCE, and its examples are that markup with
 * their own parameters. The include is resolved textually, before the
 * parse, so the parser never sees it: the included file's body is
 * inlined, and the INCLUDING file's scope decl stands (the included
 * file's own scope decl is dropped — it is the family's, and the
 * example's is narrower).
 */
async function resolveIncludes(
  source: string,
  id: string,
): Promise<{ readonly code: string }> {
  const file = id.split("?")[0]!;
  const dir = file.split("/").slice(0, -1).join("/");
  let code = source;
  // A family nests its examples one level, so an include may reach up.
  for (let pass = 0; pass < 8; pass += 1) {
    const m = /<include\s+file="([^"]+)"\s*\/?>/.exec(code);
    if (m === null) break;
    const target = m[1]!;
    const path = target.startsWith("/") ? target.slice(1) : `${dir}/${target}`;
    const resolved = path.split("/").reduce((parts, part) => {
      if (part === "..") return parts.slice(0, -1);
      if (part === ".") return parts;
      return [...parts, part];
    }, [] as string[]).join("/");
    let included: string;
    try {
      // The plugin runs in the app's runtime (Node, Bun, Deno), so the
      // file is read the way the other hooks read it.
      const fs = await import("node:fs/promises");
      included = await fs.readFile(resolved, "utf8");
    } catch {
      throw new Error(
        `spin-components: ${id} includes ${target}, which is not there`,
      );
    }
    // The included file's scope or script decl is the family's; the
    // example's stands. Only the BODY is shared.
    const body = included
      .replace(/<script(\s[^>]*)?>[\s\S]*?<\/script>\s*/, "");
    code = code.replace(m[0], body);
  }
  return { code };
}

export default spinComponentsStage;
